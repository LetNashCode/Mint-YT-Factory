# GENERATE ALL VISUALS
# ==========================================================================

def generate_images(
    script,
    workdir,
    config,
):
    """
    Generate exactly 14 AI images.

    Return format:

    [
        [
            scene_01_shot_01.png,
            scene_01_shot_02.png
        ],
        [
            scene_02_shot_01.png,
            scene_02_shot_02.png
        ],
        ...
    ]

    This structure is intentionally preserved for assemble.py.
    """

    os.makedirs(
        workdir,
        exist_ok=True,
    )

    # ----------------------------------------------------------------------
    # Validate script BEFORE contacting image provider.
    # ----------------------------------------------------------------------

    scenes = _validate_script_structure(
        script
    )

    _validate_continuity_metadata(
        script
    )

    # ----------------------------------------------------------------------
    # Dimensions
    # ----------------------------------------------------------------------

    width, height = _get_image_dimensions(
        config
    )

    # ----------------------------------------------------------------------
    # Seed
    # ----------------------------------------------------------------------

    base_seed = _get_base_seed(
        script
    )

    image_paths = []

    print("=" * 80)
    print("🎨 GENERATING AI VISUALS")
    print("=" * 80)

    print(
        f"Scenes: "
        f"{len(scenes)}"
    )

    print(
        f"Visuals per scene: "
        f"{VISUALS_PER_SCENE}"
    )

    print(
        f"Total images: "
        f"{EXPECTED_TOTAL_IMAGES}"
    )

    print(
        f"Resolution: "
        f"{width}x{height}"
    )

    print(
        f"Base seed: "
        f"{base_seed}"
    )

    print(
        f"Provider: "
        f"Pollinations AI"
    )

    print(
        f"Model: "
        f"{MODEL_NAME}"
    )

    print(
        "Continuity system: ENABLED"
    )

    print(
        "Portrait normalization: ENABLED"
    )

    print(
        "PNG validation: ENABLED"
    )

    print("=" * 80)

    # ----------------------------------------------------------------------
    # Scene generation
    # ----------------------------------------------------------------------

    for scene_index, scene in enumerate(
        scenes,
        start=1,
    ):

        visuals = scene[
            "visuals"
        ]

        scene_paths = []

        print("=" * 80)
        print(
            f"🎬 SCENE "
            f"{scene_index}/{EXPECTED_SCENES}"
        )
        print("=" * 80)

        # ------------------------------------------------------------------
        # Two shots per scene
        # ------------------------------------------------------------------

        for visual_index, visual in enumerate(
            visuals,
            start=1,
        ):

            prompt = build_prompt(
                scene,
                visual,
                script,
                scene_index,
                visual_index,
            )

            shot_seed = _get_shot_seed(
                base_seed,
                scene_index,
                visual_index,
            )

            print("=" * 80)

            print(
                f"🖼️ SHOT "
                f"{visual_index}/{VISUALS_PER_SCENE}"
            )

            print(
                f"Scene: "
                f"{scene_index}"
            )

            print(
                f"Seed: "
                f"{shot_seed}"
            )

            print(
                f"Style: "
                f"{visual.get('image_style', '')}"
            )

            print(
                f"Visual impact: "
                f"{visual.get('visual_impact', '')}"
            )

            print(
                f"Prompt: "
                f"{prompt}"
            )

            print("=" * 80)

            # --------------------------------------------------------------
            # Generate
            # --------------------------------------------------------------

            image = generate_image(
                prompt,
                width,
                height,
                shot_seed,
            )

            # --------------------------------------------------------------
            # Save
            # --------------------------------------------------------------

            filename = os.path.join(
                workdir,
                (
                    f"scene_{scene_index:02d}"
                    f"_shot_{visual_index:02d}.png"
                ),
            )

            _save_image(
                image,
                filename,
                width,
                height,
            )

            scene_paths.append(
                filename
            )

            print(
                f"✅ Saved: "
                f"{filename}"
            )

            # --------------------------------------------------------------
            # Prevent burst requests.
            # --------------------------------------------------------------

            if not (
                scene_index == EXPECTED_SCENES
                and
                visual_index == VISUALS_PER_SCENE
            ):

                time.sleep(
                    BETWEEN_IMAGE_DELAY
                )

        image_paths.append(
            scene_paths
        )

    # ==========================================================================
    # FINAL VALIDATION
    # ==========================================================================

    total_images = sum(
        len(scene_paths)
        for scene_paths in image_paths
    )

    if total_images != EXPECTED_TOTAL_IMAGES:

        raise RuntimeError(
            f"Expected exactly "
            f"{EXPECTED_TOTAL_IMAGES} generated images, "
            f"but generated "
            f"{total_images}."
        )

    # ----------------------------------------------------------------------
    # Verify every scene.
    # ----------------------------------------------------------------------

    for scene_index, scene_paths in enumerate(
        image_paths,
        start=1,
    ):

        if len(
            scene_paths
        ) != VISUALS_PER_SCENE:

            raise RuntimeError(
                f"Scene {scene_index} "
                f"contains {len(scene_paths)} "
                f"images instead of "
                f"{VISUALS_PER_SCENE}."
            )

        for visual_index, path in enumerate(
            scene_paths,
            start=1,
        ):

            if not os.path.exists(
                path
            ):

                raise RuntimeError(
                    f"Missing generated image: "
                    f"Scene {scene_index}, "
                    f"Shot {visual_index}: "
                    f"{path}"
                )

            if os.path.getsize(
                path
            ) < MIN_IMAGE_BYTES:

                raise RuntimeError(
                    f"Generated image is too small: "
                    f"{path}"
                )

            # --------------------------------------------------------------
            # Final image validation.
            # --------------------------------------------------------------

            if Image is not None:

                try:

                    with Image.open(
                        path
                    ) as image:

                        if image.format != EXPECTED_FORMAT:

                            raise RuntimeError(
                                f"Scene {scene_index} "
                                f"Shot {visual_index}: "
                                f"expected PNG, got "
                                f"{image.format}."
                            )

                        if image.size != (
                            width,
                            height,
                        ):

                            raise RuntimeError(
                                f"Scene {scene_index} "
                                f"Shot {visual_index}: "
                                f"expected "
                                f"{width}x{height}, "
                                f"got "
                                f"{image.size}."
                            )

                        image.verify()

                except Exception as error:

                    raise RuntimeError(
                        f"Final image validation failed "
                        f"for Scene {scene_index}, "
                        f"Shot {visual_index}: "
                        f"{error}"
                    )

    # ==========================================================================
    # SUMMARY
    # ==========================================================================

    print("=" * 80)
    print("✅ VISUAL GENERATION COMPLETE")
    print("=" * 80)

    print(
        f"Scenes: "
        f"{len(image_paths)}"
    )

    print(
        f"Images generated: "
        f"{total_images}"
    )

    print(
        f"Expected images: "
        f"{EXPECTED_TOTAL_IMAGES}"
    )

    print(
        f"Resolution: "
        f"{width}x{height}"
    )

    print(
        "Visual continuity: ENABLED"
    )

    print(
        "Style lock: APPLIED"
    )

    print(
        "Recurring subjects: APPLIED"
    )

    print(
        "Environment continuity: APPLIED"
    )

    print(
        "PNG normalization: COMPLETE"
    )

    print(
        "Image validation: PASSED"
    )

    print("=" * 80)

    return image_paths


