def load_config():

    with open(
        "config.yaml",
        "r",
        encoding="utf-8",
    ) as f:

        config = yaml.safe_load(f)

    if not isinstance(
        config,
        dict,
    ):

        raise RuntimeError(
            "config.yaml did not return a valid configuration."
        )

    return config


