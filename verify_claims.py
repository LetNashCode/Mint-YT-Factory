"""
verify_claims.py
Mint-YT-Factory

Version 2.1

Scientific claim verification layer.

FLOW:

Generated Script
      ↓
Extract IMPORTANT factual claims
      ↓
Use only scene-cited research sources
      ↓
Compare against verified Evidence Text
      ↓
Gemini evaluates support
      ↓
Local citation + evidence validation
      ↓
PASS / FAIL
      ↓
Only verified scripts continue

IMPORTANT:

- Gemini may ONLY use supplied Evidence Text.
- Metadata is NEVER treated as scientific evidence.
- Claims must use source IDs cited by their scene.
- Claims cannot switch to an unrelated source.
- Every important factual claim must have a valid citation.
- Every cited source must be evidence-verified.
- Evidence Text must actually exist.
- Uncertain claims FAIL.
- Unsupported claims FAIL.
- Contradicted claims FAIL.
- Invalid source IDs FAIL.
- Claims with zero source IDs FAIL.
- A scene does NOT need to contain a factual claim.
- Abstracts are accepted only when they are part of the verified
  research evidence package.
- Gemini cannot introduce outside knowledge.
- Original research source IDs are preserved exactly.
"""

import json
import os
import re

from google import genai
from google.genai import types


# ==========================================================================
# CONFIG
# ==========================================================================

MODEL_NAME = "gemini-flash-lite-latest"

MAX_CLAIMS_PER_SCENE = 8

MIN_EVIDENCE_CHARACTERS = 120


# ==========================================================================
# HELPERS
# ==========================================================================

def _clean(
    text
):

    if text is None:

        return ""

    return re.sub(
        r"\s+",
        " ",
        str(text),
    ).strip()


def _get_api_key():

    api_key = os.environ.get(
        "GEMINI_API_KEY"
    )

    if not api_key:

        raise RuntimeError(
            "GEMINI_API_KEY environment "
            "variable is missing."
        )

    return api_key


# ==========================================================================
# BUILD VERIFIED SOURCE MAP
# ==========================================================================

def _build_source_map(
    research
):
    """
    Build the authoritative source map.

    IMPORTANT:

    The source_id generated by the research layer is authoritative.

    Examples:

        doi_a0e748e41dd1
        doi_ad9aa1dac2e2
        doi_7566a56dbcf2
        doi_e5061afccac8
        doi_0b195db04e43

    DO NOT create artificial IDs such as:

        source_1
        source_2
        source_3

    The exact same source_id must travel through:

        research
            ↓
        script
            ↓
        scene source_ids
            ↓
        claim verification

    This prevents citation mismatches between the generated script
    and the research package.
    """

    sources = research.get(
        "sources",
        [],
    )

    source_map = {}

    for source in sources:

        if not isinstance(
            source,
            dict,
        ):

            continue

        # --------------------------------------------------------------
        # USE THE ORIGINAL RESEARCH SOURCE ID
        # --------------------------------------------------------------

        source_id = _clean(
            source.get(
                "source_id",
                "",
            )
        )

        if not source_id:

            continue

        source_map[
            source_id
        ] = source

    return source_map


# ==========================================================================
# BUILD RESEARCH EVIDENCE
# ==========================================================================

def _build_research_evidence(
    research
):
    """
    Build the evidence package Gemini is allowed to use.

    ONLY evidence-verified sources are presented as usable evidence.

    Metadata is explicitly separated from Evidence Text.
    """

    source_map = _build_source_map(
        research
    )

    blocks = []

    for source_id, source in source_map.items():

        title = _clean(
            source.get(
                "title",
                "",
            )
        )

        authors = _clean(
            source.get(
                "authors",
                "",
            )
        )

        journal = _clean(
            source.get(
                "journal",
                "",
            )
        )

        year = source.get(
            "year",
            "",
        )

        doi = _clean(
            source.get(
                "doi",
                "",
            )
        )

        evidence_text = _clean(
            source.get(
                "evidence_text",
                "",
            )
        )

        evidence_type = _clean(
            source.get(
                "evidence_type",
                "",
            )
        )

        evidence_quality = _clean(
            source.get(
                "evidence_quality",
                "",
            )
        )

        evidence_available = (
            source.get(
                "evidence_available",
                False,
            )
        )

        evidence_verified = (
            source.get(
                "evidence_verified",
                False,
            )
        )

        verification_level = _clean(
            source.get(
                "verification_level",
                "",
            )
        )

        # --------------------------------------------------------------
        # SAFETY GATE
        # --------------------------------------------------------------

        if evidence_verified is not True:

            continue

        if evidence_available is not True:

            continue

        if not evidence_text:

            continue

        if len(
            evidence_text
        ) < MIN_EVIDENCE_CHARACTERS:

            continue

        blocks.append(
            f"""
SOURCE ID: {source_id}

============================================================
SOURCE METADATA
============================================================

Title:
{title}

Authors:
{authors}

Journal:
{journal}

Year:
{year}

DOI:
{doi}

Verification Level:
{verification_level}

Evidence Verified:
{evidence_verified}

============================================================
SCIENTIFIC EVIDENCE
============================================================

Evidence Available:
{evidence_available}

Evidence Type:
{evidence_type}

Evidence Quality:
{evidence_quality}

Evidence Text:
{evidence_text}

============================================================
IMPORTANT
============================================================

Only the Evidence Text above may be used to support factual
claims.

The title, authors, journal, year, DOI, URL, verification level,
and evidence metadata are NOT scientific evidence.
""".strip()
        )

    if not blocks:

        return (
            "NO VERIFIED SCIENTIFIC EVIDENCE AVAILABLE."
        )

    return "\n\n".join(
        blocks
    )


# ==========================================================================
# BUILD SCRIPT CLAIM CONTEXT
# ==========================================================================

def _build_claim_context(
    script
):

    scenes = script.get(
        "scene_plan",
        [],
    )

    blocks = []

    for scene in scenes:

        if not isinstance(
            scene,
            dict,
        ):

            continue

        scene_number = scene.get(
            "scene"
        )

        narration = _clean(
            scene.get(
                "narration",
                "",
            )
        )

        source_ids = scene.get(
            "source_ids",
            [],
        )

        if not isinstance(
            source_ids,
            list,
        ):

            source_ids = []

        source_ids = [
            str(source_id).strip()
            for source_id in source_ids
            if str(source_id).strip()
        ]

        blocks.append(
            f"""
SCENE {scene_number}

Narration:
{narration}

CITED SOURCE IDS FOR THIS SCENE:
{json.dumps(source_ids)}
""".strip()
        )

    return "\n\n".join(
        blocks
    )


