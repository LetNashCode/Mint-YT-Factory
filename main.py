# HARD RESEARCH GATE
# ==========================================================================

def enforce_research_gate(
    research,
):

    if not isinstance(
        research,
        dict,
    ):

        raise RuntimeError(
            "PIPELINE STOPPED: "
            "research package is invalid."
        )

    if research.get(
        "verified"
    ) is not True:

        raise RuntimeError(
            "PIPELINE STOPPED: "
            "research package is not VERIFIED."
        )

    if research.get(
        "status"
    ) != "VERIFIED":

        raise RuntimeError(
            "PIPELINE STOPPED: "
            "research status is not VERIFIED."
        )

    sources = research.get(
        "sources",
        [],
    )

    if not isinstance(
        sources,
        list,
    ):

        raise RuntimeError(
            "PIPELINE STOPPED: "
            "research sources are invalid."
        )

    if len(
        sources
    ) < 2:

        raise RuntimeError(
            "PIPELINE STOPPED: "
            "fewer than 2 verified research sources."
        )

    usable_sources = 0

    for index, source in enumerate(
        sources,
        start=1,
    ):

        if not isinstance(
            source,
            dict,
        ):

            raise RuntimeError(
                f"PIPELINE STOPPED: "
                f"research source {index} is invalid."
            )

        if source.get(
            "verified"
        ) is not True:

            raise RuntimeError(
                f"PIPELINE STOPPED: "
                f"research source {index} is not verified."
            )

        if source.get(
            "evidence_verified"
        ) is not True:

            raise RuntimeError(
                f"PIPELINE STOPPED: "
                f"research source {index} is not evidence verified."
            )

        if source.get(
            "evidence_available"
        ) is not True:

            raise RuntimeError(
                f"PIPELINE STOPPED: "
                f"research source {index} does not have "
                f"evidence_available=True."
            )

        evidence_text = str(
            source.get(
                "evidence_text",
                "",
            )
        ).strip()

        if not evidence_text:

            raise RuntimeError(
                f"PIPELINE STOPPED: "
                f"research source {index} has no evidence_text."
            )

        if len(
            evidence_text
        ) < MIN_EVIDENCE_CHARACTERS:

            raise RuntimeError(
                f"PIPELINE STOPPED: "
                f"research source {index} evidence_text is too short. "
                f"Minimum: {MIN_EVIDENCE_CHARACTERS} characters."
            )

        usable_sources += 1

    if usable_sources < 2:

        raise RuntimeError(
            "PIPELINE STOPPED: "
            "fewer than 2 usable evidence-verified sources."
        )

    print(
        "✅ RESEARCH HARD GATE PASSED"
    )

    print(
        f"   Usable evidence sources: {usable_sources}"
    )

    return True


# ==========================================================================
# HARD CLAIM VERIFICATION GATE
# ==========================================================================

def enforce_claim_verification_gate(
    script,
):

    verification = script.get(
        "claim_verification",
        {},
    )

    if not isinstance(
        verification,
        dict,
    ):

        raise RuntimeError(
            "PIPELINE STOPPED: "
            "claim verification result is missing."
        )

    status = verification.get(
        "overall_status"
    )

    verified = (
        verification.get(
            "verified"
        )
        is True
    )

    if status != "PASS":

        print("=" * 80)
        print("❌ CLAIM VERIFICATION HARD GATE FAILED")
        print("=" * 80)

        print(
            f"Verification status: {status}"
        )

        unsupported = verification.get(
            "unsupported_claims",
            [],
        )

        warnings = verification.get(
            "warnings",
            [],
        )

        if unsupported:

            print(
                "\n❌ Unsupported / invalid claims:"
            )

            for item in unsupported:

                print(
                    f"  ❌ {item}"
                )

        if warnings:

            print(
                "\n⚠️ Uncertain claims:"
            )

            for item in warnings:

                print(
                    f"  ⚠️ {item}"
                )

        print("=" * 80)

        raise RuntimeError(
            "PIPELINE STOPPED: "
            "scientific claim verification did not PASS."
        )

    if not verified:

        raise RuntimeError(
            "PIPELINE STOPPED: "
            "claim verification status is PASS but "
            "verified flag is not True."
        )

    claims = verification.get(
        "claims",
        [],
    )

    if not isinstance(
        claims,
        list,
    ):

        raise RuntimeError(
            "PIPELINE STOPPED: "
            "claim verification claims are invalid."
        )

    for claim in claims:

        if not isinstance(
            claim,
            dict,
        ):

            raise RuntimeError(
                "PIPELINE STOPPED: "
                "claim verification contains an invalid claim."
            )

        claim_status = str(
            claim.get(
                "status",
                "",
            )
        ).strip().lower()

        if claim_status != "supported":

            raise RuntimeError(
                "PIPELINE STOPPED: "
                "claim verification contains a non-supported claim."
            )

        source_ids = claim.get(
            "source_ids",
            [],
        )

        if not isinstance(
            source_ids,
            list,
        ) or not source_ids:

            raise RuntimeError(
                "PIPELINE STOPPED: "
                "supported claim has no source IDs."
            )

    print("=" * 80)
    print("✅ CLAIM VERIFICATION HARD GATE PASSED")
    print("=" * 80)

    print(
        f"Verified claims: {len(claims)}"
    )

    return True


# ==========================================================================
# CLAIM VERIFICATION FAILURE CLASSIFICATION
# ==========================================================================

def _claim_failure_is_structural_only(
    verification,
):
    """
    True when every unsupported/warning item in the FINAL claim
    verification result looks like a structural problem
    (missing scene review, count mismatch, malformed claim object,
    etc.) rather than a genuine "the evidence does not support this"
    scientific rejection.

    verify_script_claims() already retries pure structural failures
    internally (up to its own MAX_VERIFICATION_ATTEMPTS). If, after
    those internal retries, the final result STILL only contains
    structural markers, regenerating the script is unlikely to help
    much faster than simply calling verify_script_claims() again on
    the same script — but we still route it through the outer retry
    loop below so it gets a fresh attempt rather than silently
    passing.
    """

    if not isinstance(
        verification,
        dict,
    ):
        return False

    problems = []

    problems.extend(
        verification.get(
            "unsupported_claims",
            [],
        )
        or []
    )

    problems.extend(
        verification.get(
            "warnings",
            [],
        )
        or []
    )

    if not problems:
        return False

    problems_text = "\n".join(
        str(problem).lower()
        for problem in problems
    )

    structural_markers = (
        "scene review",
        "scene reviews",
        "claim count",
        "quantitative language but gemini returned zero",
        "factual claims but returned zero",
        "returned claims but factual_claims_found",
        "verifier returned an invalid",
        "missing scene reviews",
        "returned an empty claim",
    )

    return all(
        any(
            marker in str(problem).lower()
            for marker in structural_markers
        )
        for problem in problems
    )


def _build_claim_feedback_text(
    verification,
):
    """
    Build a human-readable feedback block from a FAILED claim
    verification result, to feed back into the next script-generation
    attempt via generate_script(..., extra_feedback=...).
    """

    if not isinstance(
        verification,
        dict,
    ):
        return ""

    lines = []

    unsupported = verification.get(
        "unsupported_claims",
        [],
    )

    warnings = verification.get(
        "warnings",
        [],
    )

    if unsupported:

        lines.append(
            "REJECTED AS UNSUPPORTED / CONTRADICTED:"
        )

        for item in list(
            unsupported
        )[:MAX_FEEDBACK_ITEMS]:

            lines.append(
                f"- {item}"
            )

    if warnings:

        lines.append(
            ""
        )

        lines.append(
            "REJECTED AS UNCERTAIN (evidence related but insufficient):"
        )

        for item in list(
            warnings
        )[:MAX_FEEDBACK_ITEMS]:

            lines.append(
                f"- {item}"
            )

    return "\n".join(
        lines
    ).strip()


# ==========================================================================
# SCRIPT + CLAIM VERIFICATION CYCLE
# ==========================================================================

def generate_verified_script(
    topic,
    config,
    research,
):
    """
    Runs the script-generation -> claim-verification cycle as a unit.

    generate_script() already retries internally on its own validation
    errors (schema, duration, source IDs, claim-strength patterns,
    etc.) up to MAX_GENERATION_ATTEMPTS.

    verify_script_claims() already retries internally on pure
    structural verification problems up to its own
    MAX_VERIFICATION_ATTEMPTS, but a retry never overrides a genuine
    scientific failure by design.

    This function adds an OUTER cycle: if the final claim verification
    result is a genuine scientific failure (specific claims rejected
    as unsupported / uncertain / contradicted, not just structural
    noise), the script itself is regenerated from scratch with that
    feedback included, up to MAX_SCRIPT_CLAIM_ATTEMPTS times, before
    the pipeline gives up.
    """

    extra_feedback = ""

    last_script = None

    for cycle in range(
        1,
        MAX_SCRIPT_CLAIM_ATTEMPTS + 1,
    ):

        print("=" * 80)
        print(
            f"🔁 SCRIPT/CLAIM VERIFICATION CYCLE "
            f"{cycle}/{MAX_SCRIPT_CLAIM_ATTEMPTS}"
        )
        print("=" * 80)

        script = generate_script(
            topic,
            config,
            research,
            extra_feedback=extra_feedback,
        )

        print(
            f"Scenes: "
            f"{len(script.get('scene_plan', []))}"
        )

        print(
            "Images: "
            f"{script.get('image_generation', {}).get('total_images', 14)}"
        )

        print(
            "Verified research sources: "
            f"{len(script.get('research_sources', []))}"
        )

        next_short_topic = get_next_short_topic(
            script
        )

        print(
            "Next Short: "
            f"{next_short_topic or 'Not specified'}"
        )

        if not next_short_topic:

            raise RuntimeError(
                "PIPELINE STOPPED: "
                "script did not provide next_short.topic."
            )

        print("=" * 80)
        print("🧪 VERIFYING IMPORTANT FACTUAL CLAIMS")
        print("=" * 80)

        script = verify_script_claims(
            script,
            research,
        )

        verification = script.get(
            "claim_verification",
            {},
        )

        last_script = script

        if (
            verification.get(
                "overall_status"
            )
            == "PASS"
        ):

            print(
                f"✅ Claims verified on cycle "
                f"{cycle}/{MAX_SCRIPT_CLAIM_ATTEMPTS}."
            )

            return script

        # --------------------------------------------------------------
        # FAILED. Decide whether to retry the whole cycle.
        # --------------------------------------------------------------

        print(
            f"❌ Claim verification failed on cycle "
            f"{cycle}/{MAX_SCRIPT_CLAIM_ATTEMPTS}."
        )

        if cycle >= MAX_SCRIPT_CLAIM_ATTEMPTS:

            print(
                "⛔ No script/claim cycles remaining. "
                "Stopping with the last result."
            )

            break

        feedback_text = _build_claim_feedback_text(
            verification
        )

        if not feedback_text:

            print(
                "⚠️ No specific claim feedback available; "
                "retrying with the same prompt."
            )

        else:

            print(
                "📋 Feeding rejected claims back into "
                "the next script-generation attempt:"
            )

            print(
                feedback_text
            )

        extra_feedback = feedback_text

    return last_script


# ==========================================================================
# FINAL PUBLISHING SAFETY GATE
# ==========================================================================

def enforce_publishing_gate(
    script,
):

    publishing = script.get(
        "publishing",
        {},
    )

    if not isinstance(
        publishing,
        dict,
    ):

        raise RuntimeError(
            "PIPELINE STOPPED: "
            "publishing metadata is missing."
        )

    if publishing.get(
        "research_verified"
    ) is not True:

        raise RuntimeError(
            "PIPELINE STOPPED: "
            "script is not marked research verified."
        )

    if publishing.get(
        "citations_ready"
    ) is not True:

        raise RuntimeError(
            "PIPELINE STOPPED: "
            "citations are not ready."
        )

    if not claims_are_verified(
        script
    ):

        raise RuntimeError(
            "PIPELINE STOPPED: "
            "claims are not verified."
        )

    print(
        "✅ FINAL SCIENTIFIC PUBLISHING GATE PASSED"
    )

    return True


