def verify_script_claims(
    script,
    research,
):

    if not isinstance(
        script,
        dict,
    ):

        raise RuntimeError(
            "Claim verification received "
            "an invalid script."
        )

    if not isinstance(
        research,
        dict,
    ):

        raise RuntimeError(
            "Claim verification received "
            "invalid research."
        )

    # ----------------------------------------------------------------------
    # RESEARCH MUST BE VERIFIED
    # ----------------------------------------------------------------------

    if research.get(
        "verified"
    ) is not True:

        raise RuntimeError(
            "Claim verification requires "
            "verified research."
        )

    if research.get(
        "status"
    ) != "VERIFIED":

        raise RuntimeError(
            "Claim verification requires "
            "research status VERIFIED."
        )

    # ----------------------------------------------------------------------
    # RESEARCH MUST HAVE MULTIPLE SOURCES
    # ----------------------------------------------------------------------

    sources = research.get(
        "sources",
        [],
    )

    if not isinstance(
        sources,
        list,
    ):

        raise RuntimeError(
            "Research sources are invalid."
        )

    if len(
        sources
    ) < 2:

        raise RuntimeError(
            "Claim verification requires "
            "at least 2 research sources."
        )

    print("=" * 80)
    print("🧪 SCIENTIFIC CLAIM VERIFICATION")
    print("=" * 80)

    print(
        f"Research sources: {len(sources)}"
    )

    print(
        "Evidence policy: VERIFIED EVIDENCE TEXT ONLY"
    )

    print(
        "Citation policy: SCENE-LOCAL SOURCES ONLY"
    )

    # ----------------------------------------------------------------------
    # PRINT AUTHORITATIVE SOURCE IDS
    # ----------------------------------------------------------------------

    source_map = _build_source_map(
        research
    )

    print(
        f"Authoritative source IDs: {len(source_map)}"
    )

    for source_id in source_map:

        print(
            f"  🔗 {source_id}"
        )

    # ----------------------------------------------------------------------
    # GEMINI
    # ----------------------------------------------------------------------

    result = _verify_with_gemini(
        script,
        research,
    )

    # ----------------------------------------------------------------------
    # LOCAL SAFETY VALIDATION
    # ----------------------------------------------------------------------

    result = _local_validate(
        result,
        script,
        research,
    )

    # ----------------------------------------------------------------------
    # SAVE RESULT INTO SCRIPT
    # ----------------------------------------------------------------------

    script[
        "claim_verification"
    ] = {

        "overall_status":
            result.get(
                "overall_status",
                "FAIL",
            ),

        "claims":
            result.get(
                "claims",
                [],
            ),

        "unsupported_claims":
            result.get(
                "unsupported_claims",
                [],
            ),

        "warnings":
            result.get(
                "warnings",
                [],
            ),

        "verified":
            (
                result.get(
                    "overall_status"
                )
                == "PASS"
            ),
    }

    # ----------------------------------------------------------------------
    # OUTPUT
    # ----------------------------------------------------------------------

    if result.get(
        "overall_status"
    ) == "PASS":

        print(
            "✅ ALL IMPORTANT CLAIMS VERIFIED"
        )

    else:

        print(
            "❌ CLAIM VERIFICATION FAILED"
        )

        unsupported = result.get(
            "unsupported_claims",
            [],
        )

        warnings = result.get(
            "warnings",
            [],
        )

        if unsupported:

            print(
                "\n❌ Unsupported / invalid claims:"
            )

            for claim in unsupported:

                print(
                    f"  ❌ {claim}"
                )

        if warnings:

            print(
                "\n⚠️ Uncertain claims:"
            )

            for warning in warnings:

                print(
                    f"  ⚠️ {warning}"
                )

    print("=" * 80)

    return script


