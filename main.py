# YOUTUBE METADATA
# ==========================================================================

def build_title_description(
    script,
):
    """
    Build public YouTube metadata.

    IMPORTANT:

    The description contains ONLY information about the current Short.

    next_short is deliberately NOT included.

    Internal scientific verification information is deliberately NOT
    included.

    A concise research section is included for credibility.

    Each public research reference includes both DOI and Source URL
    whenever those fields are available.
    """

    title = str(
        script.get(
            "title",
            "Educational Short",
        )
    ).strip()

    # ----------------------------------------------------------------------
    # CURRENT TOPIC ONLY
    # ----------------------------------------------------------------------

    current_description = str(
        script.get(
            "description",
            "",
        )
    ).strip()

    next_short = script.get(
        "next_short",
        {},
    )

    next_topic = ""

    if isinstance(
        next_short,
        dict,
    ):

        next_topic = str(
            next_short.get(
                "topic",
                "",
            )
        ).strip()

    current_description = clean_public_description(
        current_description,
        next_topic,
    )

    description_parts = []

    if current_description:

        description_parts.append(
            current_description
        )

    # ----------------------------------------------------------------------
    # RESEARCH & FURTHER READING
    # ----------------------------------------------------------------------

    description_parts.append(
        build_research_section(
            script
        )
    )

    # ----------------------------------------------------------------------
    # HASHTAGS
    # ----------------------------------------------------------------------

    tags = script.get(
        "tags",
        [],
    )

    if isinstance(
        tags,
        list,
    ):

        hashtags = []

        for tag in tags:

            tag = str(
                tag
            ).strip()

            if not tag:
                continue

            tag = tag.replace(
                " ",
                "",
            ).replace(
                "#",
                "",
            )

            if tag:

                hashtags.append(
                    f"#{tag}"
                )

        if hashtags:

            description_parts.append(
                " ".join(
                    hashtags
                )
            )

    # ----------------------------------------------------------------------
    # FINAL DESCRIPTION
    # ----------------------------------------------------------------------

    final_description = "\n\n".join(
        description_parts
    ).strip()

    return (
        title[:100],
        final_description[:5000],
    )


