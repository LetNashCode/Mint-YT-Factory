# VERIFY WITH GEMINI
# ==========================================================================

def _verify_with_gemini(
    script,
    research,
):

    client = genai.Client(
        api_key=_get_api_key()
    )

    research_evidence = (
        _build_research_evidence(
            research
        )
    )

    claim_context = (
        _build_claim_context(
            script
        )
    )

    prompt = f"""
VERIFY THIS SCRIPT.

============================================================
VERIFIED SCIENTIFIC EVIDENCE
============================================================

{research_evidence}

============================================================
SCRIPT
============================================================

{claim_context}

============================================================
TASK
============================================================

Extract EVERY IMPORTANT FACTUAL CLAIM from the narration.

Do NOT invent claims.

Do NOT turn stylistic sentences into factual claims.

For each important factual claim:

1. State the claim.
2. Identify its scene.
3. Look ONLY at Evidence Text belonging to sources cited by
   that scene.
4. Do NOT use metadata as evidence.
5. Return source_ids that are a SUBSET of the scene's cited sources.
6. Preserve the exact source IDs supplied by the research package.
7. Determine whether the evidence directly supports the claim.
8. Explain why.
9. Provide a concise evidence-based explanation.

IMPORTANT:

Do NOT use a source from another scene.

Do NOT introduce outside information.

Do NOT invent evidence.

Do NOT upgrade uncertainty into certainty.

Do NOT convert correlation into causation.

Do NOT convert possibility into certainty.

Do NOT accept unsupported numbers.

If a scene contains only stylistic narration and no factual claim,
do not create an artificial claim.

Return ONLY JSON.
"""

    response = client.models.generate_content(

        model=MODEL_NAME,

        contents=prompt,

        config=types.GenerateContentConfig(

            system_instruction=
                _system_prompt(),

            response_mime_type=
                "application/json",

            response_json_schema=
                build_response_schema(),
        ),
    )

    if not response.text:

        raise RuntimeError(
            "Claim verifier returned an empty response."
        )

    try:

        return json.loads(
            response.text
        )

    except json.JSONDecodeError as error:

        raise RuntimeError(
            "Claim verifier returned invalid JSON: "
            f"{error}"
        )


# ==========================================================================
# LOCAL SAFETY VALIDATION
# ==========================================================================

def _local_validate(
    result,
    script,
    research,
):
    """
    Local safety layer.

    Gemini decides whether the evidence supports the claim.

    This function verifies that Gemini obeyed the structural rules.

    Gemini cannot bypass:

    - invalid source IDs
    - cross-scene citations
    - missing citations
    - unverified evidence
    - missing evidence text
    - uncertain status
    - unsupported status
    - contradicted status
    """

    if not isinstance(
        result,
        dict,
    ):

        raise RuntimeError(
            "Claim verifier returned "
            "an invalid result."
        )

    # ----------------------------------------------------------------------
    # AUTHORITATIVE SOURCE MAP
    # ----------------------------------------------------------------------

    source_map = _build_source_map(
        research
    )

    valid_source_ids = set(
        source_map.keys()
    )

    # ----------------------------------------------------------------------
    # VERIFY EVERY RESEARCH SOURCE IS ACTUALLY USABLE
    # ----------------------------------------------------------------------

    usable_source_ids = set()

    for source_id, source in source_map.items():

        if not isinstance(
            source,
            dict,
        ):

            continue

        if source.get(
            "evidence_verified"
        ) is not True:

            continue

        if source.get(
            "evidence_available"
        ) is not True:

            continue

        evidence_text = _clean(
            source.get(
                "evidence_text",
                "",
            )
        )

        if len(
            evidence_text
        ) < MIN_EVIDENCE_CHARACTERS:

            continue

        usable_source_ids.add(
            source_id
        )

    # ----------------------------------------------------------------------
    # BUILD SCENE → CITED SOURCES MAP
    # ----------------------------------------------------------------------

    scene_source_map = {}

    for scene in script.get(
        "scene_plan",
        [],
    ):

        if not isinstance(
            scene,
            dict,
        ):

            continue

        scene_number = scene.get(
            "scene"
        )

        source_ids = scene.get(
            "source_ids",
            [],
        )

        if not isinstance(
            source_ids,
            list,
        ):

            source_ids = []

        normalized_ids = set(

            str(source_id).strip()

            for source_id in source_ids

            if str(source_id).strip()
        )

        scene_source_map[
            scene_number
        ] = normalized_ids

    # ----------------------------------------------------------------------
    # RESULT ARRAYS
    # ----------------------------------------------------------------------

    claims = result.get(
        "claims",
        [],
    )

    if not isinstance(
        claims,
        list,
    ):

        claims = []

    unsupported = list(
        result.get(
            "unsupported_claims",
            [],
        )
        or []
    )

    warnings = list(
        result.get(
            "warnings",
            [],
        )
        or []
    )

    # ----------------------------------------------------------------------
    # CLAIM VALIDATION
    # ----------------------------------------------------------------------

    claims_per_scene = {}

    for claim in claims:

        if not isinstance(
            claim,
            dict,
        ):

            unsupported.append(
                "Verifier returned an invalid claim object."
            )

            continue

        claim_text = _clean(
            claim.get(
                "claim",
                "",
            )
        )

        if not claim_text:

            unsupported.append(
                "Verifier returned an empty claim."
            )

            continue

        try:

            scene_number = int(
                claim.get(
                    "scene",
                    0,
                )
            )

        except Exception:

            scene_number = 0

        status = _clean(
            claim.get(
                "status",
                "",
            )
        ).lower()

        reason = _clean(
            claim.get(
                "reason",
                "",
            )
        )

        evidence = _clean(
            claim.get(
                "evidence",
                "",
            )
        )

        source_ids = claim.get(
            "source_ids",
            [],
        )

        if not isinstance(
            source_ids,
            list,
        ):

            source_ids = []

        source_ids = [

            str(source_id).strip()

            for source_id in source_ids

            if str(source_id).strip()
        ]

        # --------------------------------------------------------------
        # CLAIM COUNT
        # --------------------------------------------------------------

        claims_per_scene[
            scene_number
        ] = (
            claims_per_scene.get(
                scene_number,
                0,
            )
            + 1
        )

        if (
            claims_per_scene[
                scene_number
            ]
            > MAX_CLAIMS_PER_SCENE
        ):

            unsupported.append(
                (
                    f"Scene {scene_number} has more than "
                    f"{MAX_CLAIMS_PER_SCENE} claims."
                )
            )

        # --------------------------------------------------------------
        # SCENE MUST EXIST
        # --------------------------------------------------------------

        if scene_number not in scene_source_map:

            unsupported.append(
                (
                    f"Claim references invalid scene "
                    f"{scene_number}: {claim_text}"
                )
            )

            continue

        scene_sources = scene_source_map[
            scene_number
        ]

        # --------------------------------------------------------------
        # CLAIM MUST HAVE CITATION
        # --------------------------------------------------------------

        if not source_ids:

            unsupported.append(
                (
                    f"Claim has no source citation: "
                    f"{claim_text}"
                )
            )

        # --------------------------------------------------------------
        # SOURCE IDS MUST EXIST
        # --------------------------------------------------------------

        invalid_ids = [

            source_id

            for source_id in source_ids

            if source_id not in valid_source_ids
        ]

        if invalid_ids:

            unsupported.append(
                (
                    f"Invalid source citation "
                    f"{', '.join(invalid_ids)}: "
                    f"{claim_text}"
                )
            )

        # --------------------------------------------------------------
        # SOURCES MUST BE USABLE EVIDENCE SOURCES
        # --------------------------------------------------------------

        unusable_ids = [

            source_id

            for source_id in source_ids

            if source_id not in usable_source_ids
        ]

        if unusable_ids:

            unsupported.append(
                (
                    f"Claim uses source(s) without verified "
                    f"evidence: "
                    f"{', '.join(unusable_ids)}. "
                    f"Claim: {claim_text}"
                )
            )

        # --------------------------------------------------------------
        # SOURCE IDS MUST BELONG TO THAT SCENE
        # --------------------------------------------------------------

        wrong_scene_sources = [

            source_id

            for source_id in source_ids

            if source_id not in scene_sources
        ]

        if wrong_scene_sources:

            unsupported.append(
                (
                    f"Claim uses source(s) not cited by "
                    f"scene {scene_number}: "
                    f"{', '.join(wrong_scene_sources)}. "
                    f"Claim: {claim_text}"
                )
            )

        # --------------------------------------------------------------
        # STATUS
        # --------------------------------------------------------------

        if status in {
            "unsupported",
            "contradicted",
        }:

            unsupported.append(
                claim_text
            )

        elif status == "uncertain":

            warnings.append(
                claim_text
            )

        elif status != "supported":

            unsupported.append(
                (
                    f"Claim has invalid verification status "
                    f"'{status}': {claim_text}"
                )
            )

        # --------------------------------------------------------------
        # SUPPORTED CLAIM MUST HAVE REASON + EVIDENCE
        # --------------------------------------------------------------

        if status == "supported":

            if not reason:

                unsupported.append(
                    (
                        f"Supported claim has no verification "
                        f"reason: {claim_text}"
                    )
                )

            if not evidence:

                unsupported.append(
                    (
                        f"Supported claim has no evidence "
                        f"explanation: {claim_text}"
                    )
                )

            if not source_ids:

                unsupported.append(
                    (
                        f"Supported claim has no source: "
                        f"{claim_text}"
                    )
                )

            if invalid_ids:

                unsupported.append(
                    (
                        f"Supported claim uses invalid source: "
                        f"{claim_text}"
                    )
                )

            if unusable_ids:

                unsupported.append(
                    (
                        f"Supported claim uses source without "
                        f"verified evidence: {claim_text}"
                    )
                )

            if wrong_scene_sources:

                unsupported.append(
                    (
                        f"Supported claim uses source from "
                        f"another scene: {claim_text}"
                    )
                )

    # ----------------------------------------------------------------------
    # RESEARCH ITSELF MUST HAVE MULTIPLE VERIFIED SOURCES
    # ----------------------------------------------------------------------

    if len(
        usable_source_ids
    ) < 2:

        unsupported.append(
            (
                "Research package contains fewer than "
                "2 usable evidence-verified sources."
            )
        )

    # ----------------------------------------------------------------------
    # DEDUPLICATE
    # ----------------------------------------------------------------------

    unsupported = list(
        dict.fromkeys(

            _clean(x)

            for x in unsupported

            if _clean(x)
        )
    )

    warnings = list(
        dict.fromkeys(

            _clean(x)

            for x in warnings

            if _clean(x)
        )
    )

    # ----------------------------------------------------------------------
    # FINAL STATUS
    # ----------------------------------------------------------------------

    # Warnings are failures.
    #
    # The pipeline requires zero uncertainty.

    if unsupported:

        result[
            "overall_status"
        ] = "FAIL"

    elif warnings:

        result[
            "overall_status"
        ] = "FAIL"

    else:

        result[
            "overall_status"
        ] = "PASS"

    result[
        "unsupported_claims"
    ] = unsupported

    result[
        "warnings"
    ] = warnings

    return result


