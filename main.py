def clean_public_description(
    description,
    next_topic="",
):
    """
    Convert the generated description into clean public-facing
    YouTube copy.

    The description must describe ONLY the current Short.

    Any accidental internal/next-video content generated by Gemini
    is removed before publishing.
    """

    if not description:
        return ""

    text = str(
        description
    ).strip()

    # ----------------------------------------------------------------------
    # Remove anything after an accidental NEXT SHORT section.
    # ----------------------------------------------------------------------

    next_section_patterns = [
        r"\n\s*[🔮]*\s*NEXT SHORT\b.*$",
        r"\n\s*NEXT SHORT\b.*$",
        r"\n\s*COMING NEXT\b.*$",
        r"\n\s*UP NEXT\b.*$",
    ]

    for pattern in next_section_patterns:

        text = re.sub(
            pattern,
            "",
            text,
            flags=re.IGNORECASE | re.DOTALL,
        )

    # ----------------------------------------------------------------------
    # Remove known next-topic text if Gemini accidentally placed it
    # inside the main description.
    # ----------------------------------------------------------------------

    if next_topic:

        next_topic = str(
            next_topic
        ).strip()

        if next_topic:

            escaped_topic = re.escape(
                next_topic
            )

            text = re.sub(
                escaped_topic,
                "",
                text,
                flags=re.IGNORECASE,
            )

    # ----------------------------------------------------------------------
    # Remove internal pipeline / AI verification language.
    # ----------------------------------------------------------------------

    forbidden_patterns = [

        r"scientific claim verification\s*:\s*passed",
        r"claim verification\s*:\s*passed",
        r"scientific claim verification",
        r"claim verification",
        r"verification\s*:\s*doi resolved through crossref",
        r"doi resolved through crossref",
        r"verification\s*:\s*verified",
        r"scientific claim\s*:\s*verified",
        r"research status\s*:\s*verified",
        r"research verification\s*:\s*passed",
        r"this short is generated by ai",
        r"generated by ai",
        r"ai-generated",
        r"ai generated",
        r"pipeline",
        r"internal verification",
    ]

    for pattern in forbidden_patterns:

        text = re.sub(
            pattern,
            "",
            text,
            flags=re.IGNORECASE,
        )

    # ----------------------------------------------------------------------
    # Remove excessive blank lines.
    # ----------------------------------------------------------------------

    text = re.sub(
        r"\n{3,}",
        "\n\n",
        text,
    )

    text = re.sub(
        r"[ \t]{2,}",
        " ",
        text,
    )

    return text.strip()


