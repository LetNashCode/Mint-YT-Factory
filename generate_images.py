def generate_single_image(
    prompt,
    workdir,
    filename="generated.png",
    width=DEFAULT_WIDTH,
    height=DEFAULT_HEIGHT,
    seed=None,
):
    """
    Generate one standalone image.

    This helper remains compatible with any existing scripts
    that use it independently from the main pipeline.
    """

    os.makedirs(
        workdir,
        exist_ok=True,
    )

    if seed is None:

        seed = int(
            time.time()
        )

    prompt = _clean_prompt(
        prompt
    )

    if not prompt:

        raise RuntimeError(
            "Cannot generate image "
            "with an empty prompt."
        )

    # ----------------------------------------------------------------------
    # Force portrait.
    # ----------------------------------------------------------------------

    if width >= height:

        width, height = (
            height,
            width,
        )

    image = generate_image(
        prompt,
        width,
        height,
        int(seed),
    )

    path = os.path.join(
        workdir,
        filename,
    )

    _save_image(
        image,
        path,
        width,
        height,
    )

    return path