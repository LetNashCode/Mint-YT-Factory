# ==========================================================================

def claims_are_verified(
    script,
):

    verification = script.get(
        "claim_verification",
        {},
    )

    return (

        verification.get(
            "verified"
        )
        is True

        and

        verification.get(
            "overall_status"
        )
        == "PASS"
    )


