# RESEARCH DESCRIPTION
# ==========================================================================

def build_research_section(
    script
):
    """
    Build a concise public research section.

    Public description contains:

    - paper title
    - authors
    - journal / venue
    - year
    - DOI
    - SOURCE URL

    The DOI and URL are taken directly from the verified
    research_sources stored in the script.

    It does NOT expose:

    - source IDs
    - scene mappings
    - verification logs
    - Crossref status
    - evidence text
    - internal pipeline information
    """

    sources = script.get(
        "research_sources",
        [],
    )

    if not isinstance(
        sources,
        list,
    ) or not sources:

        raise RuntimeError(
            "Cannot build description: "
            "no verified research sources found."
        )

    public_sources = sources[
        :MAX_PUBLIC_RESEARCH_SOURCES
    ]

    lines = [
        "📚 RESEARCH & FURTHER READING",
        "",
        "This Short is based on published scientific research:",
    ]

    added = 0

    for source in public_sources:

        if not isinstance(
            source,
            dict,
        ):

            continue

        # ------------------------------------------------------------------
        # Only verified sources can appear publicly.
        # ------------------------------------------------------------------

        if source.get(
            "verified"
        ) is not True:

            raise RuntimeError(
                "Cannot publish: "
                "an included research source is not verified."
            )

        # ------------------------------------------------------------------
        # SOURCE METADATA
        # ------------------------------------------------------------------

        title = str(
            source.get(
                "title",
                "",
            )
        ).strip()

        authors = str(
            source.get(
                "authors",
                "",
            )
        ).strip()

        journal = str(
            source.get(
                "journal",
                "",
            )
        ).strip()

        year = source.get(
            "year",
            "",
        )

        doi = str(
            source.get(
                "doi",
                "",
            )
        ).strip()

        # ------------------------------------------------------------------
        # IMPORTANT:
        #
        # URL is already preserved by generate_script.py from the
        # authoritative research package.
        #
        # We now explicitly publish it alongside the DOI.
        # ------------------------------------------------------------------

        url = str(
            source.get(
                "url",
                "",
            )
        ).strip()

        if not title:

            continue

        line = f"{added + 1}. {title}"

        if authors:

            line += f" — {authors}"

        if journal:

            line += f" — {journal}"

        if year:

            line += f" ({year})"

        # ------------------------------------------------------------------
        # DOI
        # ------------------------------------------------------------------

        if doi:

            line += f"\nDOI: {doi}"

        # ------------------------------------------------------------------
        # SOURCE URL
        #
        # This is intentionally independent of DOI.
        #
        # Therefore:
        #
        # DOI exists + URL exists
        #     → both are shown
        #
        # DOI exists + URL missing
        #     → DOI is shown
        #
        # DOI missing + URL exists
        #     → URL is shown
        # ------------------------------------------------------------------

        if url:

            line += f"\nSource: {url}"

        lines.append(
            line
        )

        added += 1

    if added == 0:

        raise RuntimeError(
            "No usable research sources available for public description."
        )

    return "\n\n".join(
        lines
    )


