# RESPONSE SCHEMA
# ==========================================================================

def build_response_schema():

    claim = {

        "type":
            "object",

        "properties": {

            "claim": {

                "type":
                    "string",
            },

            "scene": {

                "type":
                    "integer",
            },

            "source_ids": {

                "type":
                    "array",

                "items": {

                    "type":
                        "string",
                },
            },

            "status": {

                "type":
                    "string",

                "enum": [

                    "supported",

                    "unsupported",

                    "uncertain",

                    "contradicted",
                ],
            },

            "reason": {

                "type":
                    "string",
            },

            "evidence": {

                "type":
                    "string",
            },
        },

        "required": [

            "claim",

            "scene",

            "source_ids",

            "status",

            "reason",

            "evidence",
        ],
    }

    return {

        "type":
            "object",

        "properties": {

            "overall_status": {

                "type":
                    "string",

                "enum": [

                    "PASS",

                    "FAIL",
                ],
            },

            "claims": {

                "type":
                    "array",

                "items":
                    claim,
            },

            "unsupported_claims": {

                "type":
                    "array",

                "items": {

                    "type":
                        "string",
                },
            },

            "warnings": {

                "type":
                    "array",

                "items": {

                    "type":
                        "string",
                },
            },
        },

        "required": [

            "overall_status",

            "claims",

            "unsupported_claims",

            "warnings",
        ],
    }


